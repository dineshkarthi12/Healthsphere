export const specialtyMap = Object.fromEntries(specialties.map((s) => [s.slug, s])) as Record<SpecialtySlug, Specialty>;

export function getSpecialty(slug: string | undefined): Specialty | undefined {
  return slug ? specialtyMap[slug as SpecialtySlug] : undefined;
}

/** Inline style that exposes a specialty's tone as CSS variables. */
export function toneStyle(slug: SpecialtySlug | undefined): CSSProperties {
  if (!slug) return {};
  const t = specialtyMap[slug].tone;
  return { "--accent": t.color, "--accent-tint": t.tint, "--accent-ink": t.ink } as CSSProperties;
}
