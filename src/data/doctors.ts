function doctor(seed: Seed): Doctor {
  const parts = seed.name.replace(/^Dr\.\s*/, "").split(" ");
  return {
    consultationTypes: ["in-person", "video"],
    education: [
      { degree: "MBBS", institution: "Madras Medical College", year: 2004 },
      { degree: "MD / MS (Speciality)", institution: "AIIMS, New Delhi", year: 2008 },
    ],
    experience: [
      { role: `Senior Consultant · ${seed.title}`, place: "Current hospital", period: "2016 – Present" },
      { role: "Consultant", place: "Government General Hospital", period: "2010 – 2016" },
    ],
    reviews: defaultReviews(seed.id),
    ...seed,
    initials: (parts[0][0] + (parts[parts.length - 1][0] ?? "")).toUpperCase(),
  };
}

